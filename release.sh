#!/usr/bin/env bash
set -euo pipefail

# The argv as invoked, so a refusal can print the exact re-run command.
ORIG_ARGS=("$@")

# Release driver for plasmoid-updater: check the library's public API against
# its previous release tag on origin, then bump the workspace versions, refresh
# Cargo.lock, roll the changelog's Unreleased section to the new version,
# commit, push, tag, and create the GitHub release right after the tag push
# with the full changelog in the body (--notes FILE, required), so the notes
# ride GitHub's release email. .github/workflows/release.yml only builds the
# binary and uploads it to that release; it never creates the release or
# writes notes.
#
# crates.io publishing is out of scope for this script.

# The crate whose public API is a contract (topgrade depends on it); the binary
# has no library API to keep compatible. The shared semver-guard script holds
# SEMVER_PACKAGE, the baseline rule (read from origin, the one release.yml and
# CI use), the release-type helpers and the check invocation.
# shellcheck source=scripts/semver-guard.sh
source "$(dirname "${BASH_SOURCE[0]}")/scripts/semver-guard.sh"

RETRY=0
WORKSPACE=0
FORCE=0
VERSION=""
NOTES_FILES=()

while [ $# -gt 0 ]; do
  case "$1" in
    --retry)     RETRY=1;     shift ;;
    --workspace) WORKSPACE=1; shift ;;
    --force)     FORCE=1;     shift ;;
    --notes)
      if [ "$#" -lt 2 ]; then echo "Error: --notes requires a file path"; exit 1; fi
      case "$2" in -*) echo "Error: --notes requires a file path, got '$2'"; exit 1 ;; esac
      NOTES_FILES+=("$2"); shift 2 ;;
    -h|--help)
      cat <<'EOF'
Usage: release.sh [--retry] [--workspace] [--force] --notes FILE... <version>
  --retry      resume a partial release: skip steps already done (Cargo.toml
               bumped, commit made, branch pushed, tag created/pushed, release
               created) and (re)run the rest.
  --workspace  bump the version of every workspace member crate, any
               cross-member path-dep `version = "..."` pin, and
               [workspace.package] (members using `version.workspace = true`
               inherit it). Use when the root Cargo.toml is `[workspace]` with
               no `[package]`.
  --force      skip the --notes pr-coverage gate: allow the release even when
               the curated section doesn't mention every pr github
               autogenerates
  --notes FILE required. right after the tag is pushed, create the github
               release v<version> from github's autogenerated changelog with
               the PR list under "## What's Changed" replaced by the matching
               <version> (or Unreleased) section of each FILE, heading line
               stripped; other autogenerated sections (New Contributors, Full
               Changelog) are kept. Unless --force is passed, errors out before
               anything is bumped if the autogenerated list links a PR the FILE
               section never mentions (#N or pull URL).
               The body is set at creation time so the notes ride along in
               github's release email; CI only uploads binaries afterwards.
               Repeatable; needs gh authenticated against a github origin.

Every run sets gh as the git credential helper (gh auth setup-git, a global
git config write) when a github HTTPS origin has none.

Before its first change the script prints the resolved release plan and asks
for confirmation; pipe `y` (echo y | release.sh ...) for unattended runs.
EOF
      exit 0
      ;;
    -*) echo "Error: unknown flag: $1"; exit 1 ;;
    *)
      if [ -n "$VERSION" ]; then
        echo "Error: version already set to '${VERSION}', got '$1'"
        exit 1
      fi
      VERSION="$1"; shift
      ;;
  esac
done

if [ -z "$VERSION" ]; then
  echo "Error: No version provided"
  echo "Usage: release.sh [--retry] [--workspace] [--force] --notes FILE... <version>"
  exit 1
fi

# Refuse a malformed version up front: release.yml's validate job rejects any
# tag that is not vX.Y.Z, so a bad format would otherwise surface only after
# the commit and tag push.
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || {
  echo "Error: version must be X.Y.Z (tag v${VERSION} would be rejected by the release workflow's validate job)"
  exit 1
}

# The release body is never empty and never CI-written: this script creates the
# release from the --notes file at tag-push time, so --notes is required.
if [ "${#NOTES_FILES[@]}" -eq 0 ]; then
  echo "Error: --notes FILE is required (the release body comes from the matching section of FILE at creation time)"
  exit 1
fi

if [ ! -f "Cargo.toml" ]; then
  echo "Error: Cargo.toml not found in the current directory"
  exit 1
fi

crate_name() {
  sed -nE '/^\[package\]/,/^\[/{ s/^name = "(.*)"/\1/p; }' "${1:-Cargo.toml}" | head -n1
}
current_version() {
  sed -nE '/^\[package\]/,/^\[/{ s/^version = "(.*)"/\1/p; }' "${1:-Cargo.toml}" | head -n1
}

# Non-workspace mode on a virtual workspace root would sed the wrong line and die
# at cargo check: refuse it before any other check or mutation, naming the flag.
if [ "$WORKSPACE" -ne 1 ] && [ -z "$(crate_name || true)" ]; then
  echo "Error: root Cargo.toml has no [package] section (virtual workspace); pass --workspace"
  exit 1
fi

# Validate --notes prerequisites up front so a missing file / unauthenticated gh
# fails before we bump, commit, and tag rather than after. (--notes is required,
# so these always run.)
for f in "${NOTES_FILES[@]}"; do
  [ -f "$f" ] || { echo "Error: --notes file not found: $f"; exit 1; }
done
command -v gh >/dev/null 2>&1 || { echo "Error: --notes requires the gh CLI"; exit 1; }
gh auth status >/dev/null 2>&1 || { echo "Error: --notes requires gh to be authenticated (run: gh auth login)"; exit 1; }
notes_url=$(git config --get remote.origin.url 2>/dev/null || echo "")
case "$notes_url" in
  https://github.com/*|git@github.com:*|ssh://git@github.com/*) ;;
  *) echo "Error: --notes requires a github origin remote (got '${notes_url:-none}')"; exit 1 ;;
esac

# The API check below needs its binary: refusing here, with the other
# prerequisites, keeps a missing tool from surfacing after the bump.
command -v cargo-semver-checks >/dev/null 2>&1 || {
  echo "Error: checking the library's API needs cargo-semver-checks (install: cargo install cargo-semver-checks --version 0.51.0 --locked)"
  exit 1
}
require_semver_toolchain || exit 1

# Refuse to (re)release over an existing github release on a clean run: a clean
# re-run would collide on gh release create. --retry resumes a partial run; a
# do-over deletes the old release and tag first.
if [ "$RETRY" -ne 1 ] && gh release view "v${VERSION}" >/dev/null 2>&1; then
  echo "Error: github release v${VERSION} already exists; delete it and the tag, or rerun with --retry to resume"
  exit 1
fi

workspace_members() {
  # Print one member directory per line. Reads `members = [ ... ]` under
  # [workspace] (single- or multi-line), then glob-expands each entry and keeps
  # only directories that actually contain a Cargo.toml.
  local raw d
  awk '
    /^[[:space:]]*\[workspace\]/ { inws = 1; next }
    /^[[:space:]]*\[/           { inws = 0 }
    inws && /^[[:space:]]*members[[:space:]]*=/ { grab = 1 }
    grab {
      line = $0
      while (match(line, /"[^"]*"/)) {
        print substr(line, RSTART + 1, RLENGTH - 2)
        line = substr(line, RSTART + RLENGTH)
      }
      if (line ~ /\]/) grab = 0
    }
  ' Cargo.toml | while IFS= read -r raw; do
    # shellcheck disable=SC2086
    for d in $raw; do
      [ -f "$d/Cargo.toml" ] && printf '%s\n' "$d"
    done
  done
}
bump_workspace_versions() {
  # Bump the [package] version of the root manifest and every member, plus
  # [workspace.package] (the source for members using `version.workspace = true`),
  # then fix any cross-member path-dependency `version = "..."` pin in the root
  # manifest and every member so the workspace stays internally consistent.
  local m dep dep_re
  sed -i -E '/^\[package\]/,/^\[/ s/^version = ".*"/version = "'"${VERSION}"'"/' Cargo.toml
  sed -i -E '/^\[workspace\.package\]/,/^\[/ s/^version = ".*"/version = "'"${VERSION}"'"/' Cargo.toml
  for m in "${MEMBERS[@]}"; do
    sed -i -E '/^\[package\]/,/^\[/ s/^version = ".*"/version = "'"${VERSION}"'"/' "$m/Cargo.toml"
  done
  for dep in "${MEMBER_NAMES[@]}"; do
    dep_re=${dep//./\\.}
    sed -i -E "s|^([[:space:]]*${dep_re}[[:space:]]*=[[:space:]]*\{[^}]*version[[:space:]]*=[[:space:]]*\")[^\"]*\"|\1${VERSION}\"|" Cargo.toml
    for m in "${MEMBERS[@]}"; do
      sed -i -E "s|^([[:space:]]*${dep_re}[[:space:]]*=[[:space:]]*\{[^}]*version[[:space:]]*=[[:space:]]*\")[^\"]*\"|\1${VERSION}\"|" "$m/Cargo.toml"
    done
  done
}
commit_exists() {
  # The log is captured first: grep -q exits on its match, and a writer still
  # feeding a pipe to it takes SIGPIPE, which pipefail reads as "not found".
  local subjects
  subjects="$(git log -n 200 --format=%s -- 2>/dev/null)" || return 1
  grep -qFx -- "chore: release v${VERSION}" <<<"$subjects"
}
local_tag_exists() {
  git rev-parse --verify -q "refs/tags/v${VERSION}" >/dev/null
}
remote_tag_exists() {
  local listing
  listing="$(git ls-remote --tags origin "refs/tags/v${VERSION}" 2>/dev/null)" || return 1
  grep -qE "refs/tags/v${VERSION}\$" <<<"$listing"
}
remote_has_head() {
  local branch local_sha remote_sha
  branch=$(git symbolic-ref --short HEAD 2>/dev/null) || return 1
  git fetch --quiet origin "$branch" 2>/dev/null || return 1
  local_sha=$(git rev-parse HEAD)
  remote_sha=$(git rev-parse "origin/${branch}" 2>/dev/null) || return 1
  [ "$local_sha" = "$remote_sha" ]
}
print_rerun_command() {
  # The re-run line for a refusal: the invocation exactly as typed. $1 replaces
  # the positional version when given.
  local override_version="${1:-}" drop_retry=0 rerun_args="" a self i=0
  local -a rerun_words=()
  [ -z "$override_version" ] || drop_retry=1
  while [ "$i" -lt "${#ORIG_ARGS[@]}" ]; do
    a="${ORIG_ARGS[$i]}"
    case "$a" in
      --notes)
        rerun_words+=("$a")
        i=$((i + 1))
        rerun_words+=("${ORIG_ARGS[$i]}")
        ;;
      --retry)
        # a different version is a different release: its first run must pass
        # the "release already exists" guard, which --retry skips
        [ "$drop_retry" -eq 1 ] || rerun_words+=("$a")
        ;;
      -*) rerun_words+=("$a") ;;
      *)
        if [ -n "$override_version" ]; then rerun_words+=("$override_version"); override_version=""
        else rerun_words+=("$a"); fi
        ;;
    esac
    i=$((i + 1))
  done
  for a in "${rerun_words[@]}"; do rerun_args+=" $(printf '%q' "$a")"; done
  case "$0" in
    */*) self="$0" ;;
    *) self="./$0" ;;
  esac
  echo "  $(printf '%q' "$self")${rerun_args}" >&2
}
ensure_github_auth() {
  local url helper
  url=$(git config --get remote.origin.url 2>/dev/null || echo "")
  case "$url" in
    https://github.com/*) ;;
    *) return 0 ;;
  esac
  helper=$(git config --get-all credential.https://github.com.helper 2>/dev/null | tail -n1 || echo "")
  case "$helper" in
    *gh*auth*git-credential*) return 0 ;;
  esac
  if command -v gh >/dev/null 2>&1 && gh auth status >/dev/null 2>&1; then
    echo "Configuring gh as git credential helper"
    gh auth setup-git
  else
    echo "Warning: github HTTPS remote without gh credential helper; pushes may prompt for a password"
  fi
}
extract_version_notes() {
  # Print the body of the $VERSION section of file $1 (heading line excluded),
  # from the heading whose first token (sans a leading `v`) equals $VERSION up to
  # the next heading. Leading blank lines are trimmed; emits nothing if no match.
  awk -v ver="$VERSION" '
    /^#+[[:space:]]+/ {
      if (insec) exit
      hdr = $0
      sub(/^#+[[:space:]]+/, "", hdr); sub(/^v/, "", hdr); sub(/[[:space:]].*$/, "", hdr)
      if (hdr == ver) insec = 1
      next
    }
    insec {
      if (!seen && $0 ~ /^[[:space:]]*$/) next
      seen = 1; print
    }
  ' "$1"
}
extract_unreleased_notes() {
  # extract_version_notes for a file the changelog roll has not renamed yet:
  # the body under the first "Unreleased" heading (case-insensitive).
  awk '
    /^#+[[:space:]]+/ {
      if (insec) exit
      hdr = $0
      sub(/^#+[[:space:]]+/, "", hdr); sub(/[[:space:]].*$/, "", hdr)
      if (tolower(hdr) == "unreleased") insec = 1
      next
    }
    insec {
      if (!seen && $0 ~ /^[[:space:]]*$/) next
      seen = 1; print
    }
  ' "$1"
}
collect_version_notes() {
  # Concatenated $VERSION sections of every --notes file; a file still headed
  # "Unreleased" (pre-roll) matches via the fallback. Misses go to stderr so
  # callers can capture stdout clean.
  local f sec out=""
  for f in "${NOTES_FILES[@]}"; do
    sec="$(extract_version_notes "$f")"
    [ -z "${sec//[[:space:]]/}" ] && sec="$(extract_unreleased_notes "$f")"
    if [ -z "${sec//[[:space:]]/}" ]; then
      echo "  no ${VERSION} or Unreleased section in $f" >&2
      continue
    fi
    [ -n "$out" ] && out+=$'\n\n'
    out+="$sec"
  done
  printf '%s' "$out"
}
autogen_notes() {
  # github's autogenerated release-notes body for v$VERSION. Works before the
  # tag exists too: target_commitish anchors the preview then, and github
  # ignores it once the tag is real. previous_tag_name is passed explicitly
  # (github's auto-detect can skip back past the latest release, re-listing
  # already-shipped PRs) so the pre-bump preview and the final body agree.
  local branch args prev
  args=(--method POST "repos/{owner}/{repo}/releases/generate-notes" -f "tag_name=v${VERSION}" --jq .body)
  branch=$(git symbolic-ref --short HEAD 2>/dev/null || echo "")
  [ -n "$branch" ] && args+=(-f "target_commitish=${branch}")
  prev=$( { git tag --list 'v*'; printf 'v%s\n' "$VERSION"; } | sort -Vu \
    | awk -v cur="v${VERSION}" '$0 == cur { print last; exit } { last = $0 }' )
  [ -n "$prev" ] && args+=(-f "previous_tag_name=${prev}")
  gh api "${args[@]}" 2>/dev/null
}
whats_changed_prs() {
  # PR numbers linked under "## What's Changed" in the autogen body on stdin,
  # one per line, deduped.
  awk '/^## /{ insec = ($0 ~ /What.s Changed/) } insec' \
    | grep -oE 'https://github\.com/[^ )]*/pull/[0-9]+' \
    | sed -E 's|.*/pull/||' | sort -un || true
}
create_release_with_notes() {
  # Publish the github release right after the tag push. The body is github's
  # autogenerated changelog with the PR list under "## What's Changed" swapped
  # for the curated notes section; other autogenerated sections (New
  # Contributors, the Full Changelog link) are kept. Setting the body at
  # creation time is what lands the notes in github's "new release" email. CI
  # never creates the release or touches its notes; it only uploads binaries to
  # this release as the build finishes, so the notes ship first and the assets
  # attach a few minutes later, on purpose.
  local tag="v${VERSION}" matched autogen="" body tries=0
  matched="$(collect_version_notes)"
  [ -z "${matched//[[:space:]]/}" ] && { echo "Error: no ${VERSION} section in the --notes file(s) at create time; not creating a release without notes (fix the file, then rerun with --retry)"; exit 1; }
  # generate-notes needs the just-pushed tag visible to the API; retry briefly to
  # ride out replication lag (this also doubles as a tag-visibility wait before the
  # create below) rather than shipping the curated section alone.
  while [ "$tries" -lt 4 ]; do
    autogen="$(autogen_notes || true)"
    [ -n "${autogen//[[:space:]]/}" ] && break
    sleep 3
    tries=$((tries + 1))
  done
  if grep -q "^## What's Changed" <<<"$autogen"; then
    body="$(CURATED="$matched" awk '
      /^## What.s Changed[[:space:]]*$/ { print; print ENVIRON["CURATED"]; inlist = 1; next }
      inlist && /^\* /                  { next }
      inlist && /^[[:space:]]*$/        { if (!blanked) { print; blanked = 1 }; next }
                                        { inlist = 0; print }
    ' <<<"$autogen")"
  else
    # no PRs since the last tag: autogen is just the Full Changelog link
    body="## What's Changed"$'\n'"$matched"$'\n\n'"$autogen"
  fi
  # --retry may find the release already created by a prior run; heal it in place
  # instead of failing on a duplicate create.
  if [ "$RETRY" -eq 1 ] && gh release view "$tag" >/dev/null 2>&1; then
    echo "Updating release notes for ${tag} (already exists)"
    printf '%s\n' "$body" | gh release edit "$tag" --notes-file -
  else
    echo "Creating GitHub release ${tag} with the full changelog"
    printf '%s\n' "$body" | gh release create "$tag" --title "$tag" --notes-file - --latest --verify-tag
  fi
}

MEMBERS=()
MEMBER_NAMES=()
if [ "$WORKSPACE" -eq 1 ]; then
  while IFS= read -r m; do MEMBERS+=("$m"); done < <(workspace_members)
  if [ "${#MEMBERS[@]}" -eq 0 ]; then
    echo "Error: --workspace given but no member crates found under [workspace] in Cargo.toml"
    exit 1
  fi
  for m in "${MEMBERS[@]}"; do
    MEMBER_NAMES+=("$(crate_name "$m/Cargo.toml" || true)")
  done
  echo "Workspace members: ${MEMBERS[*]}"
  CUR_VERSION="$(current_version "${MEMBERS[0]}/Cargo.toml" || true)"
  # Members using `version.workspace = true` carry no [package] version literal;
  # the [workspace.package] section of the root manifest is their source.
  if [ -z "$CUR_VERSION" ]; then
    CUR_VERSION="$(sed -nE '/^\[workspace\.package\]/,/^\[/{ s/^version = "(.*)"/\1/p; }' Cargo.toml | head -n1 || true)"
  fi
else
  CUR_VERSION="$(current_version || true)"
fi

CHANGELOG_FILES=(docs/RELEASE_NOTES.md docs/CHANGELOG.md RELEASE_NOTES.md CHANGELOG.md)

# A release commit stages the whole index, and the push and tag publish it:
# refuse a dirty tree in every mode, --retry included, untracked files too
# (spelled out so a status.showUntrackedFiles=no config cannot hide one). The
# refusal lists the dirty paths and `git diff HEAD`, asks the operator to
# commit what to keep and discard the rest by hand, and prints the re-run line
# as typed; it reads no other state, and the script never resets, stashes or
# discards anything itself. A path is operator-controlled text, so each is
# printed shell-quoted (%q) behind `# `, one line per path with no status
# letters or arrow: the line holds only `#` and quoted words, and nothing in it
# redirects or expands in bash or in zsh, where an interactive `#` is a command
# name. Pasting the whole block runs `git diff HEAD` and the re-run line, which
# refuses again while the tree is dirty. The listing is NUL-separated so a
# newline in a path stays one record, hence a file rather than a substitution
# (which drops NULs).
dirty_file="$(mktemp)"
trap 'rm -f "$dirty_file"' EXIT
if ! git status --porcelain -z --untracked-files=normal >"$dirty_file"; then
  echo "Error: git status failed; refusing to release" >&2
  exit 1
fi
if [ -s "$dirty_file" ]; then
  echo "# Error: working tree or index not clean; the release commit stages the whole index:" >&2
  untracked_paths=()
  while IFS= read -r -d '' record; do
    dirty_path="${record:3}"
    case "${record:0:2}" in
      *[RC]*)
        # a rename or copy record is followed by the path it came from
        IFS= read -r -d '' from_path || from_path=""
        printf '  # %q %q\n' "$from_path" "$dirty_path" >&2
        ;;
      '??')
        untracked_paths+=("$dirty_path")
        printf '  # %q\n' "$dirty_path" >&2
        ;;
      *) printf '  # %q\n' "$dirty_path" >&2 ;;
    esac
  done <"$dirty_file"
  for dirty_path in ${untracked_paths[@]+"${untracked_paths[@]}"}; do
    printf '# untracked %q blocks the release: commit it, ignore it, or move it out of the tree (a --notes file can also live outside the worktree)\n' "$dirty_path" >&2
  done
  echo "# Inspect them:" >&2
  echo "  git diff HEAD" >&2
  echo "# Commit what you want to keep (notes written in place included), discard the rest yourself, then re-run:" >&2
  print_rerun_command
  exit 1
fi

# Refuse to release unless the new version is strictly greater than the current
# one. On --retry the current version may already equal the target (Cargo.toml
# was bumped by an earlier run), which is allowed. This runs after the dirty-tree
# guard, so an uncommitted bump meets the dirty-tree refusal first.
if [ "$CUR_VERSION" = "$VERSION" ]; then
  if [ "$RETRY" -ne 1 ]; then
    echo "Error: version is already ${VERSION}; bump to a higher version, or re-run with --retry if an earlier run of ${VERSION} stopped part-way"
    exit 1
  fi
elif [ -n "$CUR_VERSION" ] && ! version_lt "$CUR_VERSION" "$VERSION"; then
  echo "Error: new version ${VERSION} must be greater than current ${CUR_VERSION}"
  exit 1
fi

# --retry resumes a release at the commit its tag names: with HEAD anywhere
# else, the resume would push that HEAD and report the old tag released. Both
# the local tag and origin's are judged, before the plan and any change.
if [ "$RETRY" -eq 1 ]; then
  head_commit="$(git rev-parse HEAD)"
  if ! origin_tags="$(origin_release_tags)"; then
    echo "Error: git ls-remote --tags origin failed; cannot tell whether v${VERSION} names HEAD, so --retry did not start; nothing was pushed" >&2
    exit 1
  fi
  tagged_commits=$'local\t'"$(git rev-parse --verify --quiet "refs/tags/v${VERSION}^{commit}" || true)"
  tagged_commits+=$'\norigin\t'"$(awk -v ver="$VERSION" '$1 == ver { print $2 }' <<<"$origin_tags")"
  while IFS=$'\t' read -r tag_where tag_commit; do
    if [ -n "$tag_commit" ] && [ "$tag_commit" != "$head_commit" ]; then
      echo "Error: tag v${VERSION} on ${tag_where} names commit ${tag_commit}, but HEAD is ${head_commit}; --retry did not start and nothing was pushed" >&2
      exit 1
    fi
  done <<<"$tagged_commits"
fi

# The release body comes only from the curated section: refuse before any
# mutation when no --notes file has a section this script recognises. The
# heading's first word (a leading `v` is ignored) must equal the version, or
# be "Unreleased" (the pre-roll shape, e.g. "## Unreleased").
curated="$(collect_version_notes)"
if [ -z "${curated//[[:space:]]/}" ]; then
  echo "Error: no non-empty ${VERSION} or Unreleased section in: ${NOTES_FILES[*]} (a heading's first word must be ${VERSION}, v${VERSION} or Unreleased, e.g. '## Unreleased'); the release body would carry no notes"
  exit 1
fi

# The changelog roll renames the first Unreleased heading to the version: an
# empty section would roll into an empty version heading, and a file already
# carrying a <version> section would end up with two. Both shapes ship a
# broken changelog, so refuse before any mutation.
for f in "${CHANGELOG_FILES[@]}"; do
  if [ ! -f "$f" ] || ! grep -qE -i "^#+[[:space:]]+unreleased" "$f"; then continue; fi
  if [ -z "$(extract_unreleased_notes "$f")" ]; then
    echo "Error: $f's first Unreleased heading has no notes this script can read (its first word must be exactly Unreleased, e.g. '## Unreleased'); rolling it would put an empty ${VERSION} heading above the notes: fix that heading or move the notes under it"
    exit 1
  fi
  if grep -qE "^#+[[:space:]]+v?${VERSION}([[:space:]]|$)" "$f"; then
    echo "Error: $f already has a ${VERSION} section; rolling its Unreleased heading would produce a duplicate: rename the Unreleased heading to ${VERSION} by hand and drop the stale section"
    exit 1
  fi
done

# --notes coverage gate: every PR github's autogenerated "What's Changed" will
# link must already be mentioned (#N or its pull URL) in the curated section,
# so a forgotten bullet aborts before anything is bumped or tagged.
# --force skips this check.
if [ "$FORCE" -ne 1 ]; then
  autogen_preview="$(autogen_notes || true)"
  if [ -z "${autogen_preview//[[:space:]]/}" ]; then
    echo "Error: could not fetch github's autogenerated changelog to cross-check the --notes section"
    exit 1
  fi
  missing=""
  while IFS= read -r pr; do
    [ -n "$pr" ] || continue
    grep -qE "(#|/pull/)${pr}([^0-9]|$)" <<<"$curated" || missing+=" #${pr}"
  done < <(whats_changed_prs <<<"$autogen_preview")
  if [ -n "$missing" ]; then
    echo "Error: the ${VERSION} --notes section never mentions:${missing} (linked in github's autogenerated What's Changed; pass --force to skip)"
    exit 1
  fi
fi

# Everything above is read-only validation; print the resolved plan and require
# an explicit yes before the first mutation.
plan_rolls=()
for f in "${CHANGELOG_FILES[@]}"; do
  [ -f "$f" ] && grep -qE -i "^#+[[:space:]]+unreleased" "$f" && plan_rolls+=("$f")
done
if [ "$WORKSPACE" -eq 1 ]; then
  echo "Release plan: workspace v${CUR_VERSION:-?} -> v${VERSION}"
else
  CRATE_LABEL="$(crate_name || true)"
  echo "Release plan: ${CRATE_LABEL:-$(basename "$PWD")} v${CUR_VERSION:-?} -> v${VERSION}"
fi
echo "  - check ${SEMVER_PACKAGE}'s API against its previous release tag (an API change needs the bump that announces it)"
if [ "$WORKSPACE" -eq 1 ]; then
  echo "  - bump ${#MEMBERS[@]} member crate(s) + [workspace.package] + dep pins: ${MEMBER_NAMES[*]}"
else
  echo "  - bump Cargo.toml"
fi
echo "  - refresh Cargo.lock"
[ "${#plan_rolls[@]}" -gt 0 ] && echo "  - roll Unreleased -> ${VERSION} in: ${plan_rolls[*]}"
echo "  - commit \"chore: release v${VERSION}\""
case "$notes_url" in
  https://github.com/*) echo "  - set gh as the git credential helper if none is configured (gh auth setup-git)" ;;
esac
echo "  - push $(git symbolic-ref --short HEAD 2>/dev/null || echo HEAD) + tag v${VERSION} to origin"
echo "  - create github release v${VERSION} with notes from: ${NOTES_FILES[*]}"
[ "$RETRY" -eq 1 ] && echo "  - (--retry: already-completed steps will be skipped)"
printf 'Proceed? [y/N] '
read -r REPLY || REPLY=""
case "$REPLY" in
  y|Y|yes|YES) ;;
  *) echo "Aborted."; exit 1 ;;
esac

# The library's public API is a contract (topgrade depends on it), so a
# breaking change must carry the version bump that announces it. The check runs
# BEFORE any mutation: it compares the previous release tag against the version
# being released, with the release type passed explicitly so no bumped manifest
# is needed. A refusal leaves the tree, refs and remote untouched and prints no
# undo advice.
# The baseline comes from the shared rule (the newest origin v* tag below
# VERSION that HEAD contains), which prints its own refusal. On --retry the
# tag v<VERSION> may already exist; "below VERSION" keeps the first run's
# baseline. Status 3 means a fetch is needed first, so the same command is the
# re-run once the fetch line it printed has run.
baseline_status=0
baseline_tag="$(resolve_baseline "$VERSION" below)" || baseline_status=$?
if [ "$baseline_status" -ne 0 ]; then
  if [ "$baseline_status" -eq 3 ]; then print_rerun_command; fi
  exit 1
fi
previous_version="${baseline_tag#v}"
release_kind="$(release_type "$previous_version" "$VERSION")"
echo "Checking ${SEMVER_PACKAGE}'s API against v${previous_version} as $(release_label "$release_kind" "$previous_version")"
semver_status=0
semver_check "v${previous_version}" "$release_kind" || semver_status=$?
if [ "$semver_status" -eq 100 ]; then
  needed_kind="major"
  if [ "$release_kind" = "patch" ]; then
    minor_status=0
    semver_check "v${previous_version}" minor >/dev/null 2>&1 || minor_status=$?
    if [ "$minor_status" -eq 0 ]; then
      needed_kind="minor"
    elif [ "$minor_status" -ne 100 ]; then
      echo "Error: the ${SEMVER_PACKAGE} API check could not complete (cargo-semver-checks exited ${minor_status}); the release did not start" >&2
      print_rerun_command
      exit 1
    fi
  fi
  if [ "$needed_kind" = "minor" ]; then
    echo "Error: ${SEMVER_PACKAGE}'s public API change needs a minor version bump" >&2
  elif [ "${previous_version%%.*}" = "0" ]; then
    echo "Error: ${SEMVER_PACKAGE}'s public API change needs a major version bump (a minor one while below 1.0)" >&2
  else
    echo "Error: ${SEMVER_PACKAGE}'s public API change needs a major version bump" >&2
  fi
  # a baseline version too long to compute the next one from: refuse without a
  # re-run line, which would only repeat the refused version
  needed_next="$(needed_version "$previous_version" "$needed_kind")" || exit 1
  print_rerun_command "$needed_next"
  exit 1
elif [ "$semver_status" -ne 0 ]; then
  echo "Error: the ${SEMVER_PACKAGE} API check could not complete (cargo-semver-checks exited ${semver_status}); the release did not start" >&2
  print_rerun_command
  exit 1
fi

if [ "$RETRY" -eq 1 ] && [ "$CUR_VERSION" = "$VERSION" ]; then
  echo "Skipping Cargo.toml bump (already at ${VERSION})"
elif [ "$WORKSPACE" -eq 1 ]; then
  echo "Setting version ${VERSION} across ${#MEMBERS[@]} member crate(s)"
  bump_workspace_versions
else
  echo "Setting version ${VERSION}"
  sed -i -E '/^\[package\]/,/^\[/ s/^version = ".*"/version = "'"${VERSION}"'"/' Cargo.toml
fi

echo "Updating Cargo.lock"
if [ "$WORKSPACE" -eq 1 ]; then
  cargo check --workspace --quiet
else
  cargo check --quiet
fi

CHANGED_CHANGELOGS=()
for f in "${CHANGELOG_FILES[@]}"; do
  [ -f "$f" ] || continue
  if grep -qE -i "^#+[[:space:]]+unreleased" "$f"; then
    echo "Rolling Unreleased -> ${VERSION} in $f"
    sed -i -E "0,/^#+[[:space:]]+unreleased/I { s/^(#+[[:space:]]+)unreleased(.*)$/\\1${VERSION}\\2/I; }" "$f"
    CHANGED_CHANGELOGS+=("$f")
  fi
done

if [ "$RETRY" -eq 1 ] && commit_exists; then
  echo "Skipping commit (chore: release v${VERSION} already in history)"
else
  echo "Staging version bump"
  git add Cargo.lock
  if [ "$WORKSPACE" -eq 1 ]; then
    git add Cargo.toml
    for m in "${MEMBERS[@]}"; do
      git add "$m/Cargo.toml"
    done
  else
    git add Cargo.toml
  fi
  for f in "${CHANGED_CHANGELOGS[@]}"; do
    if git check-ignore -q "$f"; then
      echo "Skipping ignored $f"
      continue
    fi
    git add "$f"
  done
  if [ "$RETRY" -eq 1 ] && git diff --cached --quiet; then
    echo "Skipping commit (no staged changes)"
  else
    echo "Committing version bump"
    git commit -m "chore: release v${VERSION}"
  fi
fi

ensure_github_auth

if [ "$RETRY" -eq 1 ] && remote_has_head; then
  echo "Skipping git push (origin already at HEAD)"
else
  echo "Pushing main"
  git push
fi

if [ "$RETRY" -eq 1 ] && local_tag_exists; then
  echo "Skipping local tag (v${VERSION} exists)"
else
  echo "Tagging v${VERSION}"
  git tag "v${VERSION}" -m "release v${VERSION}"
fi

if [ "$RETRY" -eq 1 ] && remote_tag_exists; then
  echo "Skipping tag push (v${VERSION} on origin)"
else
  echo "Pushing v${VERSION}"
  git push origin "v${VERSION}"
fi

create_release_with_notes

echo "Done: released v${VERSION}"
